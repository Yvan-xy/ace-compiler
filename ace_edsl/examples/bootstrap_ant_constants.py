# Double-angle scalars: for j=1..r, scalar_j = -1/(2*pi)^(2^(j-r)), r=3
def get_double_angle_scalars(r=3):
    return [
        -1.0 / ((2.0 * math.pi) ** (2 ** (j - r)))
        for j in range(1, r + 1)
    ]

